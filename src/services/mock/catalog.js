export const getLanguage = (id) => LANGUAGES.find((l) => l.id === id);
export const getCountry = (id) => COUNTRIES.find((c) => c.id === id);

/** Denormalised view used almost everywhere in the UI. */
export const languageWithCountry = (language) => {
  const country = getCountry(language.countryId);
  return {
    ...language,
    country: country?.name,
    flag: country?.flag,
    iso: country?.iso,
    region: country?.region,
  };
};

export const LANGUAGES_FULL = LANGUAGES.map(languageWithCountry);

export const languagesByCountry = () =>
  COUNTRIES.map((country) => ({
    ...country,
    languages: LANGUAGES_FULL.filter((l) => l.countryId === country.id),
  })).filter((c) => c.languages.length);
